/* =============================================================================
   ARTarual — PL / EN switch

   Every visible string lives in the I18N dictionary below (en + pl for the
   same key). HTML elements opt in with data-i18n="key" (sets innerHTML) or
   data-i18n-attr="attr:key;attr2:key2" (sets an attribute instead, e.g. a
   meta description's content, or a form field's placeholder).

   products.js reads the same dictionary through t()/getLang() when it
   builds ring tiles, the configurator and the bag — see the PL fields
   (namePl, shortPl, textPl, …) next to the English ones in its DATA
   section, and the small tPick()/tRingText() helpers in its LOGIC section.
   ============================================================================= */
const LANG_KEY = 'artarual-lang';
const DEFAULT_LANG = 'en';

function getLang() {
  try { return localStorage.getItem(LANG_KEY) || DEFAULT_LANG; } catch { return DEFAULT_LANG; }
}

function t(key, lang) {
  lang = lang || getLang();
  const dict = I18N[lang] || I18N.en;
  if (dict[key] != null) return dict[key];
  if (I18N.en[key] != null) return I18N.en[key];
  return key;
}

/** Static text + attributes only — safe to call anytime, does not touch
    anything products.js renders (that would double-render on first load). */
function applyLang(lang) {
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.innerHTML = t(el.dataset.i18n, lang);
  });

  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    el.dataset.i18nAttr.split(';').forEach(pair => {
      const [attr, key] = pair.split(':').map(s => s && s.trim());
      if (attr && key) el.setAttribute(attr, t(key, lang));
    });
  });

  document.querySelectorAll('.lang-switch button').forEach(b => {
    b.setAttribute('aria-current', b.dataset.lang === lang ? 'true' : 'false');
  });
}

/** Called when someone clicks a flag: persists the choice, re-applies the
    static text, and re-runs whatever products.js already drew (tiles,
    configurator, photo wall, bag) so it comes back in the new language
    without a page reload. */
function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
  applyLang(lang);
  if (typeof renderLists === 'function') renderLists();
  if (typeof renderRing === 'function') renderRing();
  if (typeof renderPhotoWall === 'function') renderPhotoWall();
  if (typeof bagRefresh === 'function') bagRefresh();
}

document.addEventListener('DOMContentLoaded', () => {
  applyLang(getLang());
  document.querySelectorAll('.lang-switch button').forEach(b => {
    b.addEventListener('click', () => setLang(b.dataset.lang));
  });
});


